def get_blue_book_sections() -> dict[str, dict]:
    """Return Blue Book UB sections formatted for the sections database.

    Keys use the "UB_<serial>" format matching existing Data.xml conventions.
    Each value includes family, name, h, b, tw, tf, and mass_per_m.
    """
    sections = {}
    for serial, props in UB_SECTIONS.items():
        sec_id = f"UB_{serial}"
        sections[sec_id] = {
            "family": "UB",
            "name": f"UB {serial.replace('x', ' x ')}",
            "h": props["h"],
            "b": props["b"],
            "tw": props["tw"],
            "tf": props["tf"],
            "mass_per_m": props["mass_per_m"],
        }
    return sections
